import os
import json
import random
import shutil
from pathlib import Path

import chromadb
from langchain_chroma import Chroma
from langchain_core.documents import Document
from langchain_openai import OpenAIEmbeddings


# ============================================================
# Experiment configuration
# ============================================================

SEED = 42

# Fraction of the final memory database that is poisoned
POISON_RATES = [0.00, 0.10, 0.25, 0.50, 0.75, 1.00]

# Keep total database size identical for every condition.
# If fewer memories are available, the script automatically reduces this.
TARGET_MEMORY_COUNT = 100

SOURCE_ROOT = Path("memory_db")

OUTPUT_ROOT = Path("memory_db/poison_rate_sweep")

ATTACK_TOOLS_FILE = Path("data/attack_tools.jsonl")
ATTACK_TOOLS_TEST_FILE = Path("data/attack_tools_test.jsonl")


random.seed(SEED)


# ============================================================
# Load attacker-tool names
# ============================================================

def load_attack_tool_names():
    tool_names = set()

    possible_files = [
        ATTACK_TOOLS_FILE,
        ATTACK_TOOLS_TEST_FILE
    ]

    for path in possible_files:
        if not path.exists():
            continue

        print(f"Reading attacker tools from: {path}")

        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()

                if not line:
                    continue

                try:
                    row = json.loads(line)

                    tool_name = row.get("Attacker Tool")

                    if tool_name:
                        tool_names.add(tool_name.strip())

                except json.JSONDecodeError:
                    pass

    return sorted(tool_names)


# ============================================================
# Determine whether a stored workflow is poisoned
# ============================================================

def is_poisoned(document, attack_tool_names):

    text = document.lower()

    for tool in attack_tool_names:
        if tool.lower() in text:
            return True

    return False


# ============================================================
# Discover existing Chroma databases
# ============================================================

def find_chroma_databases():

    databases = []

    for sqlite_file in SOURCE_ROOT.rglob("chroma.sqlite3"):

        db_dir = sqlite_file.parent

        # Never use databases generated by this script as sources
        if OUTPUT_ROOT in db_dir.parents or db_dir == OUTPUT_ROOT:
            continue

        databases.append(db_dir)

    return databases


# ============================================================
# Read documents directly from Chroma
# ============================================================

def read_database(db_path):

    documents = []

    try:
        client = chromadb.PersistentClient(path=str(db_path))

        collections = client.list_collections()

        for collection_info in collections:

            collection_name = (
                collection_info.name
                if hasattr(collection_info, "name")
                else str(collection_info)
            )

            collection = client.get_collection(collection_name)

            data = collection.get(
                include=["documents", "metadatas"]
            )

            docs = data.get("documents", [])
            metas = data.get("metadatas", [])

            for i, doc in enumerate(docs):

                if not doc:
                    continue

                metadata = {}

                if i < len(metas) and metas[i]:
                    metadata = metas[i]

                documents.append({
                    "document": doc,
                    "metadata": metadata,
                    "source_database": str(db_path)
                })

    except Exception as e:
        print(f"Skipping {db_path}: {e}")

    return documents


# ============================================================
# Remove duplicate memories
# ============================================================

def deduplicate(memories):

    seen = set()
    unique = []

    for item in memories:

        document = item["document"]

        if document in seen:
            continue

        seen.add(document)

        unique.append(item)

    return unique


# ============================================================
# Main
# ============================================================

def main():

    print("=" * 60)
    print("ASB POISONING-RATE SWEEP DATABASE BUILDER")
    print("=" * 60)

    attack_tool_names = load_attack_tool_names()

    print(f"\nLoaded {len(attack_tool_names)} attacker tool names.")

    if len(attack_tool_names) == 0:
        raise RuntimeError(
            "No attacker-tool names were found."
        )

    databases = find_chroma_databases()

    print(f"\nFound {len(databases)} existing Chroma databases.")

    all_memories = []

    for db in databases:

        memories = read_database(db)

        print(
            f"{db}: {len(memories)} memories"
        )

        all_memories.extend(memories)

    all_memories = deduplicate(all_memories)

    print(
        f"\nUnique memories discovered: {len(all_memories)}"
    )

    clean_memories = []
    poisoned_memories = []

    for item in all_memories:

        if is_poisoned(
            item["document"],
            attack_tool_names
        ):
            poisoned_memories.append(item)

        else:
            clean_memories.append(item)

    print(f"Clean memories:    {len(clean_memories)}")
    print(f"Poisoned memories: {len(poisoned_memories)}")

    if not clean_memories:
        raise RuntimeError(
            "No clean memories were found in the existing ASB databases."
        )

    if not poisoned_memories:
        raise RuntimeError(
            "No poisoned memories were found in the existing ASB databases."
        )

    #
    # Determine the largest fixed database size that supports
    # every requested contamination condition.
    #
    total_count = min(
        TARGET_MEMORY_COUNT,
        len(clean_memories),
        len(poisoned_memories)
    )

    print(
        f"\nUsing fixed memory count: {total_count}"
    )

    embedding_function = OpenAIEmbeddings(
        openai_api_key=os.getenv("OPENAI_API_KEY")
    )

    manifest = []

    for poison_rate in POISON_RATES:

        poison_count = round(
            total_count * poison_rate
        )

        clean_count = total_count - poison_count

        #
        # Deterministic sampling.
        #
        rng = random.Random(
            SEED + int(poison_rate * 1000)
        )

        selected_clean = rng.sample(
            clean_memories,
            clean_count
        )

        selected_poison = rng.sample(
            poisoned_memories,
            poison_count
        )

        selected = (
            selected_clean +
            selected_poison
        )

        rng.shuffle(selected)

        rate_percent = int(poison_rate * 100)

        output_dir = (
            OUTPUT_ROOT /
            f"rate_{rate_percent}"
        )

        #
        # Remove previous version of this experimental DB.
        #
        if output_dir.exists():
            shutil.rmtree(output_dir)

        output_dir.mkdir(
            parents=True,
            exist_ok=True
        )

        docs = []

        for item in selected:

            metadata = dict(item["metadata"])

            poisoned = is_poisoned(
                item["document"],
                attack_tool_names
            )

            metadata["poisoned"] = poisoned

            metadata["poison_rate"] = poison_rate

            metadata["source_database"] = (
                item["source_database"]
            )

            docs.append(
                Document(
                    page_content=item["document"],
                    metadata=metadata
                )
            )

        vectorstore = Chroma(
            persist_directory=str(output_dir),
            embedding_function=embedding_function
        )

        vectorstore.add_documents(
            documents=docs
        )

        actual_poison = sum(
            1
            for doc in docs
            if doc.metadata["poisoned"]
        )

        actual_clean = (
            len(docs) -
            actual_poison
        )

        print()
        print(
            f"Created rate_{rate_percent}"
        )

        print(
            f"  Total:    {len(docs)}"
        )

        print(
            f"  Clean:    {actual_clean}"
        )

        print(
            f"  Poisoned: {actual_poison}"
        )

        manifest.append({
            "poison_rate": poison_rate,
            "poison_percent": rate_percent,
            "total_memories": len(docs),
            "clean_memories": actual_clean,
            "poisoned_memories": actual_poison,
            "database": str(output_dir)
        })

    #
    # Save experiment description
    #
    OUTPUT_ROOT.mkdir(
        parents=True,
        exist_ok=True
    )

    manifest_file = (
        OUTPUT_ROOT /
        "manifest.json"
    )

    with open(
        manifest_file,
        "w",
        encoding="utf-8"
    ) as f:

        json.dump(
            {
                "seed": SEED,
                "target_memory_count": total_count,
                "poison_rates": POISON_RATES,
                "conditions": manifest
            },
            f,
            indent=2
        )

    print()
    print("=" * 60)
    print("POISONING-RATE DATABASES COMPLETE")
    print("=" * 60)

    print(
        f"Manifest: {manifest_file}"
    )


if __name__ == "__main__":
    main()